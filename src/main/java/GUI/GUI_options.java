    // UPDATE LAF
    public static void updateLAFRecursively(Window window) {
        for (Window childWindow : window.getOwnedWindows()) {
            updateLAFRecursively(childWindow);
        }
        SwingUtilities.updateComponentTreeUI(window);
    }

    // HANDLE CONFIG FILE
    void loadFromConfig() {
        try {
            try (FileReader fileReader = new FileReader(configFile)) {
                Properties properties = new Properties();
                properties.load(fileReader);

                selectedLafTheme = properties.getProperty("LookAndFeel");
            }
        } catch (FileNotFoundException ex) {
            // file does not exist
        } catch (IOException ex) {
            // I/O error
        }
    }

    void saveToConfig() {
        try {
            Properties props = new Properties();
            props.setProperty("LookAndFeel", selectedLafTheme);
            try (FileWriter fileWriter = new FileWriter(configFile)) {
                props.store(fileWriter, "LAF settings");
            }
        } catch (FileNotFoundException ex) {
            // file does not exist
        } catch (IOException ex) {
            // I/O error
        }
    }

    private void btn_saveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_saveActionPerformed
        selectedLafTheme = cmb_themes.getSelectedItem().toString();
        if (selectedLafTheme.equals("FlatDarkLaf")) {
            selectedLAF = new FlatDarkLaf();
        } else {
            selectedLAF = new FlatLightLaf();
        }

        if (UIManager.getLookAndFeel().getClass().getName().equals(selectedLAF.getName())) {
            return;
        }
        try {
            UIManager.setLookAndFeel(selectedLAF);
            for (Frame frame : Frame.getFrames()) {
                updateLAFRecursively(frame);
            }
        } catch (UnsupportedLookAndFeelException e) {
            JOptionPane.showMessageDialog(null, "Failed to initialize theme.");
        }
        updateLAFRecursively(this);
        saveToConfig();

        this.dispose();
    }//GEN-LAST:event_btn_saveActionPerformed

